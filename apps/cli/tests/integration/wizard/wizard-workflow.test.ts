describe('Complete Wizard Workflow', () => {
  let testDir: string;
  let wizardService: WizardService;
  let rollbackService: RollbackService;

  // Mock modules before any test runs
  beforeAll(() => {
    // Create a file system store for this test suite
    const testFileSystem = new Map<string, string>();

    // Mock Node.js fs module for complete isolation
    const originalWriteFileSync = require('node:fs').writeFileSync;
    const originalReadFileSync = require('node:fs').readFileSync;
    const originalExistsSync = require('node:fs').existsSync;

    mock.module('node:fs', () => ({
      writeFileSync: (path: string, content: string) => {
        // Only intercept files in our test directory
        if (path.includes('/temp/wizard-isolation-')) {
          testFileSystem.set(path, content);
          // Still call original to maintain file system consistency
          return originalWriteFileSync(path, content);
        }
        return originalWriteFileSync(path, content);
      },
      readFileSync: (path: string, encoding?: string) => {
        // Only intercept files in our test directory
        if (path.includes('/temp/wizard-isolation-')) {
          if (testFileSystem.has(path)) {
            return testFileSystem.get(path);
          }
        }
        return originalReadFileSync(path, encoding);
      },
      existsSync: (path: string) => {
        // Only intercept files in our test directory
        if (path.includes('/temp/wizard-isolation-')) {
          // Check test file system first, then real file system
          if (testFileSystem.has(path)) {
            return true;
          }
          return originalExistsSync(path);
        }
        return originalExistsSync(path);
      },
      // Pass through all other fs functions
      mkdirSync: require('node:fs').mkdirSync,
      rmSync: require('node:fs').rmSync,
      unlinkSync: (path: string) => {
        // Only intercept files in our test directory
        if (path.includes('/temp/wizard-isolation-')) {
          testFileSystem.delete(path);
        }
        return require('node:fs').unlinkSync(path);
      },
    }));

    mock.module('@dev-quality/core', () => ({
      AutoConfigurationDetectionEngine: class MockDetectionEngine {
        constructor() {
          this.cache = new Map();
        }

        clearCache() {
          this.cache.clear();
        }

        async detectProject() {
          return {
            name: 'test-project',
            version: '1.0.0',
            type: 'typescript',
            frameworks: [],
            hasTypeScript: true,
            description: 'Test project',
          };
        }

        async detectTools() {
          return [];
        }

        async detectConfigs() {
          return [];
        }

        async detectDependencies() {
          return [];
        }

        async detectStructure() {
          return {
            sourceDirectories: ['./src'],
            testDirectories: ['./tests'],
            configDirectories: ['./'],
            complexity: 'simple',
            isMonorepo: false,
            packages: [],
            workspaceType: 'npm',
          };
        }

        async detectAll() {
          return createMockDetectionResult();
        }
      }
    }));

    // Store reference to test file system
    (globalThis as any).testFileSystem = testFileSystem;
  });

  // Helper function to create mock detection result with complete structure
  function createMockDetectionResult(): DetectionResult {
    return {
      project: {
        name: 'test-project',
        version: '1.0.0',
        type: 'typescript',
        frameworks: [],
        hasTypeScript: true,
        description: 'Test project',
      },
      tools: [],
      configs: [],
      dependencies: [],
      structure: {
        sourceDirectories: ['./src'],
        testDirectories: ['./tests'],
        configDirectories: ['./'],
        complexity: 'simple',
        isMonorepo: false,
        packages: [],
        workspaceType: 'npm',
      },
      issues: [],
      recommendations: [],
      timestamp: new Date().toISOString(),
    };
  }

  beforeEach(async () => {
    // Create completely isolated test directory with unique namespace for each test
    const crypto = require('node:crypto');
    const testNamespace = `wizard-isolation-${Date.now()}-${Math.random().toString(36).substring(2)}`;
    const uniqueId = crypto.randomBytes(12).toString('hex');
    testDir = createTestDir(`${testNamespace}-${uniqueId}`);

    // Force complete cache isolation
    const detectionEngine = new AutoConfigurationDetectionEngine();
    detectionEngine.clearCache();

    // Create services with isolated path
    wizardService = new WizardService(testDir);
    rollbackService = new RollbackService(testDir);

    // Create a minimal package.json for testing
    writeFileSync(
      join(testDir, 'package.json'),
      JSON.stringify({
        name: `${testNamespace}-test-project`,
        version: '1.0.0',
        description: 'Test project',
        main: 'index.js',
        scripts: {
          test: 'bun test',
        },
      })
    );

    // Ensure src and tests directories exist
    const { mkdirSync } = require('node:fs');
    mkdirSync(join(testDir, 'src'), { recursive: true });
    mkdirSync(join(testDir, 'tests'), { recursive: true });

    // Create isolation marker to detect interference
    writeFileSync(join(testDir, '.wizard-test-isolation'), JSON.stringify({
      namespace: testNamespace,
      timestamp: Date.now(),
      testId: uniqueId
    }));

    // Store testNamespace for use in test
    (globalThis as any).currentTestNamespace = testNamespace;
  });

  afterEach(() => {
    cleanupTestDir(testDir);

    // Clean up our test file system store
    const testFileSystem = (globalThis as any).testFileSystem;
    if (testFileSystem) {
      // Clear files for this test directory
      for (const [filePath] of testFileSystem.entries()) {
        if (filePath.includes(testDir)) {
          testFileSystem.delete(filePath);
        }
      }
    }

    // Additional cleanup: ensure no backup directories remain
    const { existsSync, rmSync } = require('node:fs');
    const backupDir = join(testDir, '.devquality-backup');
    if (existsSync(backupDir)) {
      rmSync(backupDir, { recursive: true, force: true });
    }
  });

  afterAll(() => {
    // Restore all mocks after all tests complete
    mock.restore();
  });

  it('should complete full workflow: generate, validate, no rollback needed', async () => {
    // Verify isolation marker exists
    const isolationMarker = readFileSync(join(testDir, '.wizard-test-isolation'), 'utf-8');
    const isolationData = JSON.parse(isolationMarker);
    const currentTestNamespace = (globalThis as any).currentTestNamespace;
    expect(isolationData.namespace).toBe(currentTestNamespace);

    // Step 1: Create backup (this will create empty backup files since they don't exist yet)
    await rollbackService.createBackup(
      ['bunfig.toml', 'eslint.config.js', '.prettierrc.json', 'tsconfig.json'],
      'configuration'
    );

    // Step 2: Generate all configurations using mocked generators
    const bunGenerator = createMockBunGenerator(testDir);
    const eslintGenerator = createMockESLintGenerator(testDir);
    const prettierGenerator = createMockPrettierGenerator(testDir);
    const tsGenerator = createMockTypeScriptGenerator(testDir);

    const bunResult = await bunGenerator.generate('create');
    const eslintResult = await eslintGenerator.generate('create');
    const prettierResult = await prettierGenerator.generate('create');
    const tsResult = await tsGenerator.generate('create');

    // Write files to disk to simulate real behavior
    writeFileSync(bunResult.filePath, bunResult.content);
    writeFileSync(eslintResult.filePath, eslintResult.content);
    writeFileSync(prettierResult.filePath, prettierResult.content);
    writeFileSync(tsResult.filePath, tsResult.content);

    // Step 3: Verify results are correct
    expect(bunResult.content).toContain('[test]');
    expect(eslintResult.content).toContain('export default');
    expect(prettierResult.content).toContain('"semi"');
    expect(tsResult.content).toContain('compilerOptions');

    wizardService.addGeneratedFile(bunResult.filePath);
    wizardService.addGeneratedFile(eslintResult.filePath);
    wizardService.addGeneratedFile(prettierResult.filePath);
    wizardService.addGeneratedFile(tsResult.filePath);

    // Step 4: Verify file content is correct by reading from disk
    const actualBunContent = readFileSync(join(testDir, 'bunfig.toml'), 'utf-8');
    const actualEslintContent = readFileSync(join(testDir, 'eslint.config.js'), 'utf-8');
    const actualPrettierContent = readFileSync(join(testDir, '.prettierrc.json'), 'utf-8');
    const actualTsContent = readFileSync(join(testDir, 'tsconfig.json'), 'utf-8');

    expect(actualBunContent).toContain('[test]');
    expect(actualBunContent).toContain('coverage = true');
    expect(actualEslintContent.length).toBeGreaterThan(100);
    expect(actualPrettierContent).toContain('"semi"');
    expect(actualTsContent).toContain('compilerOptions');

    // Step 5: Verify all files exist
    expect(existsSync(join(testDir, 'bunfig.toml'))).toBe(true);
    expect(existsSync(join(testDir, 'eslint.config.js'))).toBe(true);
    expect(existsSync(join(testDir, '.prettierrc.json'))).toBe(true);
    expect(existsSync(join(testDir, 'tsconfig.json'))).toBe(true);

    // Step 6: Cleanup backup
    await rollbackService.cleanupBackup();

    const generatedFiles = wizardService.getGeneratedFiles();
    expect(generatedFiles).toHaveLength(4);
  });

  it('should handle existing configurations with merge', async () => {
    // Create existing configs
    writeFileSync(join(testDir, 'bunfig.toml'), '[install]\nfrozen = true');
    writeFileSync(join(testDir, '.prettierrc.json'), '{"semi": false}');
    writeFileSync(
      join(testDir, 'tsconfig.json'),
      JSON.stringify({ compilerOptions: { target: 'ES2020' } })
    );

    // Create backup
    await rollbackService.createBackup(
      ['bunfig.toml', '.prettierrc.json', 'tsconfig.json'],
      'merge-test'
    );

    // Generate with merge using mocked generators that support merge
    const bunGenerator = createMockBunGenerator(testDir);
    const prettierGenerator = createMockPrettierGenerator(testDir);
    const tsGenerator = createMockTypeScriptGenerator(testDir);

    // Simulate merge behavior by reading existing content and preserving it
    const existingBunContent = readFileSync(join(testDir, 'bunfig.toml'), 'utf-8');
    const existingPrettierContent = readFileSync(join(testDir, '.prettierrc.json'), 'utf-8');
    const existingTsContent = readFileSync(join(testDir, 'tsconfig.json'), 'utf-8');

    // For merge, preserve existing settings
    const mergedBunResult = await bunGenerator.generate('merge');
    const mergedBunContent = `${existingBunContent}\n\n${mergedBunResult.content}`;
    writeFileSync(mergedBunResult.filePath, mergedBunContent);

    // For JSON configs, merge the content
    const existingPrettierConfig = JSON.parse(existingPrettierContent);
    const prettierResult = await prettierGenerator.generate('merge');
    const prettierConfig = { ...JSON.parse(prettierResult.content), ...existingPrettierConfig };
    writeFileSync(prettierResult.filePath, JSON.stringify(prettierConfig, null, 2));

    const existingTsConfig = JSON.parse(existingTsContent);
    const tsResult = await tsGenerator.generate('merge');
    const mergedTsConfig = {
      ...JSON.parse(tsResult.content),
      ...existingTsConfig,
      compilerOptions: {
        ...JSON.parse(tsResult.content).compilerOptions,
        ...existingTsConfig.compilerOptions
      }
    };
    writeFileSync(tsResult.filePath, JSON.stringify(mergedTsConfig, null, 2));

    // Verify merge preserved existing settings
    const finalBunContent = readFileSync(join(testDir, 'bunfig.toml'), 'utf-8');
    expect(finalBunContent).toContain('[install]');
    expect(finalBunContent).toContain('[test]');

    const finalPrettierContent = readFileSync(join(testDir, '.prettierrc.json'), 'utf-8');
    const finalPrettierConfig = JSON.parse(finalPrettierContent);
    expect(finalPrettierConfig.semi).toBe(false); // Preserved

    const finalTsContent = readFileSync(join(testDir, 'tsconfig.json'), 'utf-8');
    const finalTsConfig = JSON.parse(finalTsContent);
    expect(finalTsConfig.compilerOptions.target).toBe('ES2020'); // Preserved
  });

  it('should rollback on validation failure', async () => {
    // Create existing config
    const originalContent = '{"compilerOptions": {"target": "ES2020"}}';
    writeFileSync(join(testDir, 'tsconfig.json'), originalContent);

    // Create backup
    await rollbackService.createBackup(['tsconfig.json'], 'validation-test');

    // Corrupt the config
    const corruptedContent = '{invalid json}';
    writeFileSync(join(testDir, 'tsconfig.json'), corruptedContent);

    // Verify file is actually corrupted
    const actualCorruptedContent = readFileSync(join(testDir, 'tsconfig.json'), 'utf-8');
    expect(actualCorruptedContent).toBe(corruptedContent);

    // Rollback
    const rollbackResult = await rollbackService.rollback();
    expect(rollbackResult.success).toBe(true);

    // Verify original content restored
    const restoredContent = readFileSync(join(testDir, 'tsconfig.json'), 'utf-8');
    expect(restoredContent).toBe(originalContent);
  });

  it('should handle wizard cancellation with complete rollback', async () => {
    // Step 1: Generate some configs
    await rollbackService.createBackup(['bunfig.toml', 'tsconfig.json'], 'cancellation-test');

    const bunGenerator = createMockBunGenerator(testDir);
    const tsGenerator = createMockTypeScriptGenerator(testDir);

    const bunResult = await bunGenerator.generate('create');
    const tsResult = await tsGenerator.generate('create');

    // Write files to disk
    writeFileSync(bunResult.filePath, bunResult.content);
    writeFileSync(tsResult.filePath, tsResult.content);

    expect(existsSync(join(testDir, 'bunfig.toml'))).toBe(true);
    expect(existsSync(join(testDir, 'tsconfig.json'))).toBe(true);

    // Step 2: User cancels wizard - rollback everything
    const rollbackResult = await rollbackService.rollback();

    expect(rollbackResult.success).toBe(true);
    expect(existsSync(join(testDir, 'bunfig.toml'))).toBe(false);
    expect(existsSync(join(testDir, 'tsconfig.json'))).toBe(false);
  });

  it('should handle JavaScript-only project', async () => {
    // Update package.json to be JavaScript-only
    writeFileSync(
      join(testDir, 'package.json'),
      JSON.stringify({
        name: 'js-project',
        version: '1.0.0',
        main: 'index.js',
      })
    );

    // Generate configs (TypeScript optional for JS projects)
    const bunGenerator = createMockBunGenerator(testDir);
    const eslintGenerator = createMockESLintGenerator(testDir);
    const prettierGenerator = createMockPrettierGenerator(testDir);

    const bunResult = await bunGenerator.generate('create');
    const eslintResult = await eslintGenerator.generate('create');
    const prettierResult = await prettierGenerator.generate('create');

    // Write files to disk
    writeFileSync(bunResult.filePath, bunResult.content);
    writeFileSync(eslintResult.filePath, eslintResult.content);
    writeFileSync(prettierResult.filePath, prettierResult.content);

    // Verify configs exist
    expect(existsSync(join(testDir, 'bunfig.toml'))).toBe(true);
    expect(existsSync(join(testDir, 'eslint.config.js'))).toBe(true);
    expect(existsSync(join(testDir, '.prettierrc.json'))).toBe(true);
  });

  it('should persist configuration to context', async () => {
    const bunGenerator = createMockBunGenerator(testDir);
    const result = await bunGenerator.generate('create');

    wizardService.addGeneratedFile(result.filePath);

    const context = wizardService.getContext();
    expect(context.generatedFiles).toContain(result.filePath);
  });
});
